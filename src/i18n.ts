import te from './i18n/te.json';
import ur from './i18n/ur.json';

/**
 * NDLI Club Main Portal — i18n runtime (S4).
 *
 * Design:
 * - Keys are the NATURAL ENGLISH STRINGS themselves (generated by the S3 codemod),
 *   so the English UI needs zero resource entries: a missing key renders as-is.
 * - Every listed language has a REAL catalogue (flat map, keys = English strings):
 *   `hi.json` is curated Hindi; the other 18 are machine-drafted catalogues
 *   (review-pending), generated with protected tokens (IDs, dates, URLs,
 *   acronyms, emails) preserved byte-exact.
 * - keySeparator/nsSeparator are DISABLED on purpose: our keys are prose and
 *   contain dots ("0.4 seconds"), colons ("(AISHE:"), and slashes ("NAD-ABC"),
 *   which must never be parsed as nesting/namespace syntax.
 * - RTL: Urdu and Sindhi (Perso-Arabic) set `dir=rtl` on <html> at switch time.
 */

export const SUPPORTED_LANG_CODES = [
  'en', 'hi', 'as', 'bn', 'doi', 'gu', 'kn', 'kok', 'mai', 'ml',
  'mr', 'ne', 'or', 'pa', 'sa', 'sat', 'sd', 'ta', 'te', 'ur',
];

const RTL_LANG_CODES = ['ur', 'sd'];

type Catalog = Record<string, string>;

const resources: Record<string, { translation: Catalog }> = {
  en: { translation: {} },
  hi: { translation: hi as Catalog },
  as: { translation: asLang as Catalog },
  bn: { translation: bn as Catalog },
  doi: { translation: doi as Catalog },
  gu: { translation: gu as Catalog },
  kn: { translation: kn as Catalog },
  kok: { translation: kok as Catalog },
  mai: { translation: mai as Catalog },
  ml: { translation: ml as Catalog },
  mr: { translation: mr as Catalog },
  ne: { translation: ne as Catalog },
  or: { translation: or as Catalog },
  pa: { translation: pa as Catalog },
  sa: { translation: sa as Catalog },
  sat: { translation: sat as Catalog },
  sd: { translation: sd as Catalog },
  ta: { translation: ta as Catalog },
  te: { translation: te as Catalog },
  ur: { translation: ur as Catalog },
};

void i18n.init({
  resources,
  lng: 'en',
  fallbackLng: 'en',
  supportedLngs: SUPPORTED_LANG_CODES,
  keySeparator: false,
  nsSeparator: false,
  interpolation: { escapeValue: false },
  returnEmptyString: false,
  returnNull: false,
});

/** Translate one natural-key string. Missing keys fall back to the key itself (English). */
export function t(key: string, opts?: Record<string, unknown>): string {
  return i18n.t(key, opts as never) as unknown as string;
}

/** Switch UI language; keep <html lang> (WCAG 3.1.1) and <html dir> in sync. */
export function changeLanguage(code: string): void {
  void i18n.changeLanguage(code);
  if (typeof document !== 'undefined') {
    document.documentElement.lang = code;
    document.documentElement.dir = RTL_LANG_CODES.includes(code) ? 'rtl' : 'ltr';
  }
}

export default i18n;
